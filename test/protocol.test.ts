test('parseAdvertisement: real WT3 advertisement from pyAdaxLocal issue #19', () => {
  const raw = Buffer.from([11, 4, 0, 1, 116, 77, 189, 79, 56, 68, 0, 30, 133, 181, 1, 0, 0, 0, 0, 39, 108, 58]);
  const adv = parseAdvertisement(raw);
  assert.ok(adv);
  assert.equal(adv.type, 11);
  assert.equal(adv.status, 4);
  assert.equal(adv.registered, false);
  assert.equal(adv.managed, false);
  assert.equal(adv.deviceId, '409352214100036'); // same as pyAdaxLocal find_mac_id
  assert.equal(adv.wifiMac, '74:4d:bd:4f:38:44');
  assert.equal(isAvailableForProvisioning(adv), true);
});

test('parseAdvertisement: registered / managed / unknown type are not available', () => {
  const base = [5, 0, 0, 1, 116, 77, 189, 79, 56, 68];
  assert.equal(isAvailableForProvisioning(parseAdvertisement(Buffer.from(base))!), true);
  assert.equal(isAvailableForProvisioning(parseAdvertisement(Buffer.from([5, 1, ...base.slice(2)]))!), false);
  assert.equal(isAvailableForProvisioning(parseAdvertisement(Buffer.from([5, 2, ...base.slice(2)]))!), false);
  // Unknown types are allowed (flagged via isKnownType)
  const unknown = parseAdvertisement(Buffer.from([42, 0, ...base.slice(2)]))!;
  assert.equal(isAvailableForProvisioning(unknown), true);
  assert.equal(isKnownType(unknown), false);
  assert.equal(isAvailableForProvisioning(parseAdvertisement(Buffer.from([5, 0, 0, 0, 0, 0, 0, 0, 0, 0]))!), false);
});

test('parseAdvertisement: type 8 Gen 2 heater seen on Homey Pro (2026-11)', () => {
  const adv = parseAdvertisement(Buffer.from('0800000180646fa1b2c3001e85630100000000000000', 'hex'))!;
  assert.equal(adv.type, 8);
  assert.equal(adv.status, 0);
  assert.equal(adv.wifiMac, '80:64:6f:a1:b2:c3');
  assert.equal(isAvailableForProvisioning(adv), true);
  assert.equal(isKnownType(adv), false);
});

test('parseAdvertisement: too short / missing data', () => {
  assert.equal(parseAdvertisement(Buffer.from([5, 0, 1])), null);
  assert.equal(parseAdvertisement(undefined), null);
});

test('pyQuote matches Python urllib.parse.quote', () => {
  // Expected values generated with Python 3.13 urllib.parse.quote()
  assert.equal(pyQuote('abc'), 'abc');
  assert.equal(pyQuote("!'()*/ æøå"), '%21%27%28%29%2A/%20%C3%A6%C3%B8%C3%A5');
  assert.equal(pyQuote('Min WiFi #1'), 'Min%20WiFi%20%231');
  assert.equal(pyQuote('p@ss&w=rd%~._-'), 'p%40ss%26w%3Drd%25~._-');
  assert.equal(pyQuote('a+b?c'), 'a%2Bb%3Fc');
});

test('buildJoinCommand + chunkCommand match pyAdaxLocal byte for byte', () => {
  const command = buildJoinCommand('Min WiFi', 'hemmelig!', '0123456789abcdef0123');
  assert.equal(command.toString('ascii'), 'command=join&ssid=Min%20WiFi&psk=hemmelig%21&token=0123456789abcdef0123');
  // Expected chunks generated by running pyAdaxLocal's write_command logic in Python.
  assert.deepEqual(chunkCommand(command).map((c) => c.toString('hex')), [
    '0000636f6d6d616e643d6a6f696e2673736964',
    '01003d4d696e253230576946692670736b3d68',
    '0200656d6d656c696725323126746f6b656e3d',
    '03003031323334353637383961626364656630',
    '0401313233',
  ]);
});

test('chunkCommand boundaries', () => {
  const bytes = (n: number) => Buffer.alloc(n, 0x61);
  assert.equal(chunkCommand(bytes(0)).length, 0);

  const c17 = chunkCommand(bytes(17));
  assert.equal(c17.length, 1);
  assert.deepEqual([...c17[0].subarray(0, 2)], [0, 1]);
  assert.equal(c17[0].length, 19);

  const c18 = chunkCommand(bytes(18));
  assert.equal(c18.length, 2);
  assert.deepEqual([...c18[0].subarray(0, 2)], [0, 0]);
  assert.deepEqual([...c18[1]], [1, 1, 0x61]);

  const c35 = chunkCommand(bytes(35));
  assert.equal(c35.length, 3);
  assert.deepEqual(c35.map((c) => c.length), [19, 19, 3]);
  assert.ok(c35.every((c) => c.length <= 19));
});

test('generateToken: 20 lowercase hex chars, unique', () => {
  const a = generateToken();
  assert.match(a, /^[0-9a-f]{20}$/);
  assert.notEqual(a, generateToken());
});

test('parseJoinNotification', () => {
  assert.deepEqual(parseJoinNotification(Buffer.from([0, 192, 168, 1, 50])), { kind: 'joined', ip: '192.168.1.50' });
  assert.deepEqual(parseJoinNotification(Buffer.from([1])), { kind: 'invalid_wifi' });
  assert.deepEqual(parseJoinNotification(Buffer.from([0])), { kind: 'other', status: 0 });
  assert.deepEqual(parseJoinNotification(Buffer.from([0, 0, 0, 0, 0])), { kind: 'other', status: 0 });
  assert.deepEqual(parseJoinNotification(Buffer.from([7, 1, 2])), { kind: 'other', status: 7 });
  assert.deepEqual(parseJoinNotification(Buffer.alloc(0)), { kind: 'other', status: null });
});

test('UUID normalization handles Homey formats', () => {
  assert.equal(normalizeUuid(ADAX_BLE_SERVICE_UUID), '3885cc107c184ad4a48dbf11abf7cb92');
  assert.ok(uuidEquals('cc11', ADAX_BLE_COMMAND_UUID));
  assert.ok(uuidEquals('0000CC11', ADAX_BLE_COMMAND_UUID));
  assert.ok(uuidEquals('0000cc1100001000800000805f9b34fb', ADAX_BLE_COMMAND_UUID));
  assert.ok(!uuidEquals('cc12', ADAX_BLE_COMMAND_UUID));
});

test('subnetCandidates', () => {
  const c = subnetCandidates('192.168.1.50');
  assert.equal(c.length, 254);
  assert.equal(c[0], '192.168.1.1');
  assert.equal(c[253], '192.168.1.254');
  assert.deepEqual(subnetCandidates('not-an-ip'), []);
});
